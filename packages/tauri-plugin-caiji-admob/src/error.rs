use serde::{ser::Serializer, Serialize};

pub type Result<T> = std::result::Result<T, Error>;

#[derive(Debug, thiserror::Error)]
pub enum Error {
  #[error(transparent)]
  Io(#[from] std::io::Error),
  #[cfg(mobile)]
  #[error(transparent)]
  PluginInvoke(#[from] tauri::plugin::mobile::PluginInvokeError),
  /// Every ad call on desktop. AdMob has no desktop SDK, and we deliberately fail instead of
  /// returning a fake success — see the module comment in src/desktop.rs.
  #[cfg(desktop)]
  #[error("AdMob is not supported on this platform (Android only)")]
  UnsupportedPlatform,
}

impl Serialize for Error {
  fn serialize<S>(&self, serializer: S) -> std::result::Result<S::Ok, S::Error>
  where
    S: Serializer,
  {
    serializer.serialize_str(self.to_string().as_ref())
  }
}
